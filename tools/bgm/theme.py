BAR = 6  # 8분음표 6개가 6/8 한 마디

# --- 음이름 → MIDI 번호 ---------------------------------------------------

_PC = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def pitch(name):
    """'A4' 'Bb4' 'C#5' → MIDI 번호. (A4 = 69)"""
    letter, rest = name[0], name[1:]
    semi = _PC[letter]
    while rest and rest[0] in "b#":
        semi += -1 if rest[0] == "b" else 1
        rest = rest[1:]
    return semi + (int(rest) + 1) * 12


TONIC = pitch("Eb0") % 12          # E♭ = 3

# 자연단음계는 3·6·7음을 반음 내린다. E♭ 장조 기준으로 솔·도·레다.
_MINOR_FLATTEN = {(TONIC + i) % 12 for i in (4, 9, 11)}


def to_minor(notes):
    """E♭ 장조 → E♭ 평행단조. 3·6·7음을 반음 내린다.

    **7음도 반드시 함께 내린다.** 안 내리면 화성단음계가 되어 6음과 7음 사이에
    증2도가 생기는데, 설계 문서 6절이 그 소리를 금지한다 (이국적으로 들려
    「여백」의 정서와 어긋난다).
    """
    return [(s, d, p - 1 if p % 12 in _MINOR_FLATTEN else p) for (s, d, p) in notes]


def shift(notes, bars=0, semitones=0, octaves=0):
    """악구를 마디/반음/옥타브 단위로 옮긴다."""
    d = semitones + 12 * octaves
    return [(s + bars * BAR, dur, p + d) for (s, dur, p) in notes]


def _n(spec):
    """('A4', 시작, 길이) 목록을 (시작, 길이, MIDI) 목록으로."""
    return [(s, d, pitch(name)) for (name, s, d) in spec]


