# --- 화성 -----------------------------------------------------------------
#
# 3화음이 기본. 마디 3-6이 **왕도진행(IV-V-iii-vi)** 이고,
# 마디 7의 D♭(♭VII)이 「뭉클함」이 나오는 유일한 자리다. 남발하면 죽는다.

_QUALITY = {"maj": (0, 4, 7), "min": (0, 3, 7)}


def chord(name):
    """'Eb' 'Gm' 'Eb/G' 'Db' → (베이스 음이름, [구성음 음이름])"""
    head, _, bass = name.partition("/")
    if head.endswith("m"):
        root, quality = head[:-1], "min"
    else:
        root, quality = head, "maj"
    root_pc = pitch(root + "0") % 12
    tones = [(root_pc + i) % 12 for i in _QUALITY[quality]]
    bass_pc = (pitch(bass + "0") % 12) if bass else root_pc
    return bass_pc, tones


def voice(name, low=55, high=70):
    """화음을 지정한 음역 안에 배치한다."""
    _, tones = chord(name)
    out = []
    for pc in tones:
        p = low + (pc - low) % 12
        if p > high:
            p -= 12
        out.append(p)
    return sorted(out)


def bass_pitch(name, low=36, high=47):
    """화음의 베이스 음을 저역에 배치한다 (기본 C2–B2)."""
    bass_pc, _ = chord(name)
    p = low + (bass_pc - low) % 12
    return p - 12 if p > high else p


