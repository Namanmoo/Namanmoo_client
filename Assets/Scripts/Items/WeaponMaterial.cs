/// <summary>
/// 무기가 무엇으로 되어 있는가. 효과음을 고르는 데 쓴다.
///
/// 무기 타입(<see cref="WeaponType"/>)이 "어떻게 쓰는가"라면 이쪽은 "무엇인가"다.
/// 둘은 독립이다 — 만든 무기는 타입이 무작위로 정해지므로 그림이 쇠몽둥이여도
/// 총처럼 발사될 수 있고, 그때 나야 하는 소리는 "쇠가 튀어나가는 소리"다.
///
/// 소리는 동작에 붙어야 화면과 맞으므로, 재질은 동작을 고른 뒤 그 위에 얹는다.
/// </summary>
public enum WeaponMaterial
{
    /// <summary>
    /// 재질을 모르거나 따지지 않는다. 효과음을 찾을 때 재질 축을 버리고
    /// 동작만으로 고른다 — 재질별 소리를 아직 넣지 않아도 소리가 나게 하는 기본값이다.
    /// </summary>
    Any,
    Metal,
    Wood,
    Stone,
    Organic,
    Liquid,
    Magic,
    Cloth
}
